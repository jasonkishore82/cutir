// Builds the Cutir MCP server into one file inside the Claude Code plugin (plugin/server/cutir-mcp.mjs).
// The bundle includes the MCP SDK, ws and Cutir's own tool definitions, so the plugin needs no npm install.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "rolldown";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const pkg = JSON.parse(readFileSync(join(here, "package.json"), "utf8"));

// data the server serves without the editor: the animation guide and the version
writeFileSync(
  join(here, "src", "generated.ts"),
  `// Generated by mcp/build.mjs. Do not edit.\nexport const VERSION = ${JSON.stringify(pkg.version)};\nexport const ANIMATION_DOC = ${JSON.stringify(readFileSync(join(root, "docs", "ANIMATION.md"), "utf8"))};\n`
);

const outDir = join(root, "plugin", "server");
mkdirSync(outDir, { recursive: true });
await build({
  input: join(here, "src", "server.ts"),
  platform: "node",
  logLevel: "warn",
  // optional native speed-ups of ws; it works without them
  external: ["bufferutil", "utf-8-validate"],
  output: { file: join(outDir, "cutir-mcp.mjs"), format: "esm", banner: "// Cutir MCP server (bundled). Source: mcp/src/server.ts" },
});
console.log("built plugin/server/cutir-mcp.mjs");
